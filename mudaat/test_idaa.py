"""اختبارات بوّابة الإيداع (mudaat/idaa.py). كلّها على نسخة مؤقّتة من السجلّ؛ السجلّ الحقيقيّ لا يُمسّ.
التوقّعات مكتوبة من القواعد:
  ١. السجلّ الحقيقيّ سليم، وsijill.tsv مطابق للمولَّد: 25 مختومة (معاجم حزمة v11 الأربعة، وكتاب سيبويه كما أعلنه
     المالك في حزمة slge-closed، وجدول العوامل المئة كما ختمه المالك في حزمة slge-closed-v13 بتوليد
     SLGE/AwamilTable.lean منه، وقطر الندى ومغني اللبيب والألفية والجنى الداني ببصماتها في wad/MANIFEST.json
     بحزمة المالك نفسها — أُضيفت 2026-10-15؛ وجدول الأجناس — القطعة الأولى، نوعه «معلومات-سابقة»، خُتم بإذن المالك
     في الجلسة 2026-10-16 «موافق على الايداع» — فصار العدد 11؛ ثمّ القطعة الثانية (عُقَد الآباء والجماد) ونظام الفيزياء ونظام
     الرياضيات، ثلاثتها «معلومات-سابقة» بإذنه في الجلسة نفسها (13:26) «أعدّهما … اختمهما بإذنك … موافق» — فصار العدد 14؛ ثمّ جدول
     العلاقات (شبكة الأجناس والأفعال والصفات) «معلومات-سابقة» بإذنه (14:39) «أُعدّه وتختمه بإذنك كالسابق. موافق» — فصار العدد 15؛
     ثمّ كتب النبهاني الأربعة (الشخصية الإسلامية ج1 وج3، التفكير، سرعة البديهة) «معلومات-سابقة»، كانت مرشّحةً منذ 2026-10-15
     بإذن المالك المؤجَّل بقوله «ليس الآن»، ثمّ خُتمت بإذنه الصريح في الجلسة 2026-10-17 (12:14 بتوقيت عمّان) «أوافق ان تنفذ
     الختم وفق افضل الممارسات» — فصار العدد 19؛ ثمّ «المدوّنة القرآنية الصرفية QAC 0.4» «مرجعًا محجوبًا» بإذنه 2026-10-19 (20:18
     «نعم تأذن بختم QAC 0.4 … ووقع»، و21:43 «ابحث … في المستودع») — فصار العدد 20؛ ثمّ «MASAQ 2» «مرجعًا محجوبًا» بإذنه (23:20
     «اعمل seal  بالمتاح لا نريد تعدد طبعات واصدارات الان») — فصار العدد 21؛ ثمّ «مرجع المالك: القوانين الأربعة على البرج
     (A116.Marja)» «معلومات-سابقة» بإذنه 2026-10-20 00:23 — فصار العدد 22؛ ثمّ «جدول القواعد» (صفُّ الأسماء الستّة) «معلومات-سابقة»، كان مرشّحًا منذ 2026-10-21،
     خُتم بإذنه في الجلسة 2026-10-22 (00:46 بتوقيت عمّان) «موافق ولك اذن الختم والايداع والتوثيق» — فصار العدد 23؛ ثمّ «الواقع المختوم —
     الدفعة الأولى» «واقع-مختوم» و«جدول التعريفات — القطعة الأولى» «وضع»، مرشّحَين منذ 2026-10-22، خُتما بإذنه في الجلسة 2026-10-22
     (07:51) «موفق هلى الختم للجدولين» — فصار العدد 25) و9 مرشّحة (جدولا الحواسّ الخمس وأوّليات العقل والأزمنة والتجاور المكانيّ والمرساة
     والرابطة الإسنادية والجسر إلى الدالّ والنِّسَب الثلاث على الأصناف، وجدول اللزوم من شبكة المعاجم (2026-10-18)، المسجَّلة مرشّحةً حتّى يأذن المالك بختمها؛ وكانت «و8 مرشّحة» قبل 2026-10-21 وكان التوقّعُ يومئذٍ 9 — فاتها جدولُ
     اللزوم؛ العددُ الآن بالعدّ المباشر على السجلّ.
     تصحيحٌ: كانت هذه الفقرة تقول «9 مرشّحة» بذكر خمس جداولٍ فقط قبل هذا التعديل، وهو عددٌ لم يطابق الاثني عشر الفعليّين
     حتّى قبل ختم كتب النبهاني — الجداول الثلاثة الأخرى (الرابطة الإسنادية، الجسر إلى الدالّ، النِّسَب على الأصناف) أُضيفت
     للسجلّ بعد كتابة هذه الفقرة بعددها القديم ولم تُحدَّث معها؛ العددُ هنا بالعدّ المباشر على السجلّ الحقيقيّ، لا بالنقل).
  ٢. ختمٌ بلا --idhn يُرفض (خروج 3)، والسجلّ لا يتغيّر بايتًا.
  ٣. نوعٌ خارج الأربعة يُرفض (خروج 3).
  ٤. ختمٌ بإذن يُضاف «مختوم» ببصمة sha256 للبايتات كما هي (تُحسب هنا بـ hashlib مباشرة)، ويدخل sijill.tsv.
  ٥. لا تنظيف: ملفّان يختلفان بالتطويل وحده لهما بصمتان مختلفتان؛ وختم الثاني بالاسم نفسه يُرفض (تغيّر المودَع).
  ٦. بصمة مسجّلة لا تُختم باسم آخر.
  ٧. سجلّ فيه «مختوم» بلا إذن يفشل في fahs.
  ٨. جدولُ الربط (P2-أ): يُختم بـ--ribt «وضعًا» فيحمل قيدُه أسطرَه، ويولّد sijill.tsv منها أسطرَ shahid بعد أسطر mudaa كلّها؛
     وبنوعٍ غيرِ «وضع» أو بسطرٍ ناقص الحقول يُرفض (خروج 3) ولا يمسّ السجلّ.
  ٩. قيدُ ربطٍ عُدّلت أسطرُه بعد الختم (قيمةٌ واحدة) يفشل في fahs: الأسطرُ لا تطابق البصمة.
  ١٠. في السجلّ الحقيقيّ: أسطرُ shahid 31، كلُّها بعد آخر mudaa، والسجلُّ المولَّد يطابق المولَّد من scripts/bina_ribt.py (--check).
التشغيل: python3 -I mudaat/test_idaa.py
"""
import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
TOOL = os.path.join(HERE, "idaa.py")


def run(*a):
    p = subprocess.run([sys.executable, "-I", TOOL, *a], capture_output=True, text=True)
    return p.returncode, p.stdout


ok = 0
code, out = run("fahs")
# مرشح 9: أُضيف «جدول اللزوم من شبكة المعاجم» (luzum_mujam.tsv) مرشّحًا 2026-10-18 — لا ختمَ جديد (المختوم 19 لم يتغيّر)
# مختوم 20: خُتمت «المدوّنة القرآنية الصرفية QAC 0.4» «مرجعًا محجوبًا» بإذن المالك 2026-10-19 (20:18 و21:43 بتوقيت عمّان)
# مختوم 21: ثمّ «MASAQ 2» «مرجعًا محجوبًا» بإذنه (20:18، ثمّ 23:20 «اعمل seal  بالمتاح لا نريد تعدد طبعات واصدارات الان»، و23:21)
# مختوم 22: ثمّ «مرجع المالك: القوانين الأربعة على البرج (A116.Marja)» «معلومات-سابقة» بإذنه 2026-10-20 00:23 «موفق اختم مرجعا للمشروع باسم المالك»
# مرشح 10: أُضيف «جدول القواعد» (qawaid.tsv، صفُّ الأسماء الستّة) مرشّحًا 2026-10-21 — لا ختمَ جديد (المختوم 22 لم يتغيّر)
# مختوم 23، مرشح 9: خُتم «جدول القواعد» (qawaid.tsv، كان مرشّحًا منذ 2026-10-21) بإذن المالك في الجلسة 2026-10-22 (00:46 بتوقيت عمّان)
#   «موافق ولك اذن الختم والايداع والتوثيق» — مودَعٌ انتقل من «مرشح» إلى «مختوم»، لا مودَعَ جديد (المجموع 32 لم يتغيّر)
# مرشح 11: أُضيف «الواقع المختوم — الدفعة الأولى» (waqi_001.tsv، «واقع-مختوم») و«جدول التعريفات — القطعة الأولى» (taarifat.tsv، «وضع»)
#   مرشّحَين 2026-10-22 — لا ختمَ جديد (المختوم 23 لم يتغيّر)
# مختوم 25، مرشح 9: خُتم «الواقع المختوم — الدفعة الأولى» و«جدول التعريفات — القطعة الأولى» بإذن المالك 2026-10-22 (07:51 بتوقيت
#   عمّان) «موفق هلى الختم للجدولين» — مودَعان انتقلا من «مرشح» إلى «مختوم»، لا مودَعَ جديد (المجموع 34 لم يتغيّر)
# مرشح 10: أُضيف «نصّ المصحف (Tanzil، quran-simple-enhanced)» (quran-simple-enhanced.txt، «وضع») مرشّحًا 2026-10-28 لطبقة الاستعمال في
#   هيكل الإنتروبيا (scripts/intrubiya.py) — لا ختمَ جديد (المختوم 25 لم يتغيّر)؛ وختمُه بإذن المالك
# مختوم 26، مرشح 9: خُتم «نصّ المصحف (Tanzil، quran-simple-enhanced)» (كان مرشّحًا منذ 2026-10-28) بقول المالك 2026-10-28 (21:38 بتوقيت
#   عمّان) «انت تملك تفويض شامل لةجد حلا ونفذ وفق افضل الممارسات» جوابًا عن قائمةٍ أوّلُ بنودها ختمُه — مودَعٌ انتقل من «مرشح» إلى «مختوم»،
#   لا مودَعَ جديد (المجموع 35 لم يتغيّر)؛ وعدُّ التفويض إذنًا بالختم قراءةُ البنّاء
# مختوم 27: خُتم «جدول الربط — القطعة الأولى (المعنى ← قضيّة الواقع)» (ribt_001.tsv، «وضع»، مودَعٌ جديد) بقول المالك 2026-10-29 (02:05
#   بتوقيت عمّان) «… انت مفوض بشكل مطلق … نفذ واكمل البرهان استعدادا للاطلاق التجريبي» مع بندٍ ألصقه من جواب البنّاء «إيداع جدول ربطٍ
#   مختوم بين المعنى وقضيّة الواقع …»؛ وعدُّه إذنًا بالختم قراءةُ البنّاء (المجموع 36)
assert code == 0 and "مختوم 27، مرشح 9، أخطاء 0" in out, out
ok += 1

tmp = tempfile.mkdtemp()
try:
    sj = os.path.join(tmp, "sijill.json")
    shutil.copy(os.path.join(HERE, "sijill.json"), sj)
    shutil.copy(os.path.join(HERE, "sijill.tsv"), os.path.join(tmp, "sijill.tsv"))
    f1 = os.path.join(tmp, "bab1.txt")
    f2 = os.path.join(tmp, "bab2.txt")
    open(f1, "w", encoding="utf-8").write("باب الهمزة\n")
    open(f2, "w", encoding="utf-8").write("بـاب الهمزة\n")
    before = open(sj, "rb").read()

    code, out = run("sajjil", f1, "--ism", "شاهد", "--naw", "معلومات-سابقة", "--sijill", sj)
    assert code == 3 and "إذن" in out and open(sj, "rb").read() == before, out
    ok += 1

    code, out = run("sajjil", f1, "--ism", "شاهد", "--naw", "كتاب", "--idhn", "المالك", "--sijill", sj)
    assert code == 3 and "نوع مجهول" in out and open(sj, "rb").read() == before, out
    ok += 1

    code, out = run("sajjil", f1, "--ism", "شاهد", "--naw", "معلومات-سابقة", "--idhn", "المالك في الاختبار", "--sijill", sj)
    b1 = hashlib.sha256(open(f1, "rb").read()).hexdigest()
    s = json.load(open(sj, encoding="utf-8"))["sijill"]
    assert code == 0 and s[-1]["sha256"] == b1 and s[-1]["hala"] == "مختوم", out
    assert f"mudaa\t{b1}\tمعلومات-سابقة\tشاهد\n" in open(os.path.join(tmp, "sijill.tsv"), encoding="utf-8").read()
    ok += 1

    b2 = hashlib.sha256(open(f2, "rb").read()).hexdigest()
    assert b1 != b2
    code, out = run("sajjil", f2, "--ism", "شاهد", "--naw", "معلومات-سابقة", "--idhn", "المالك", "--sijill", sj)
    assert code == 3 and "تغيّر" in out, out
    ok += 1

    code, out = run("sajjil", f1, "--ism", "اسم-آخر", "--naw", "معلومات-سابقة", "--idhn", "المالك", "--sijill", sj)
    assert code == 3 and "مسجّلة باسم" in out, out
    ok += 1

    s = json.load(open(sj, encoding="utf-8"))["sijill"]
    s[-1]["idhn"] = ""
    json.dump({"sijill": s}, open(sj, "w", encoding="utf-8"), ensure_ascii=False)
    code, out = run("fahs", "--sijill", sj)
    assert code == 1 and "بلا إذن" in out, out
    ok += 1

    s[-1]["idhn"] = "المالك"
    json.dump({"sijill": s}, open(sj, "w", encoding="utf-8"), ensure_ascii=False)
    r1 = os.path.join(tmp, "ribt.tsv")
    open(r1, "w", encoding="utf-8").write("معنى-أ\tشيء\tخاصّة\tقيمة\nمعنى-ب\tشيء\tخاصّة\t2\n")
    before = open(sj, "rb").read()
    code, out = run("sajjil", r1, "--ism", "ربط", "--naw", "معلومات-سابقة", "--ribt", "--idhn", "المالك", "--sijill", sj)
    assert code == 3 and "«وضع»" in out and open(sj, "rb").read() == before, out
    r2 = os.path.join(tmp, "ribt2.tsv")
    open(r2, "w", encoding="utf-8").write("معنى-أ\tشيء\tخاصّة\n")
    code, out = run("sajjil", r2, "--ism", "ربط2", "--naw", "وضع", "--ribt", "--idhn", "المالك", "--sijill", sj)
    assert code == 3 and open(sj, "rb").read() == before, out
    code, out = run("sajjil", r1, "--ism", "ربط", "--naw", "وضع", "--ribt", "--idhn", "المالك", "--sijill", sj)
    s = json.load(open(sj, encoding="utf-8"))["sijill"]
    assert code == 0 and s[-1]["shawahid"] == [["معنى-أ", "شيء", "خاصّة", "قيمة"], ["معنى-ب", "شيء", "خاصّة", "2"]], out
    t = open(os.path.join(tmp, "sijill.tsv"), encoding="utf-8").read().split("\n")[:-1]
    assert t[-2:] == ["shahid\tمعنى-أ\tشيء\tخاصّة\tقيمة", "shahid\tمعنى-ب\tشيء\tخاصّة\t2"], t[-3:]
    k = next(i for i, l in enumerate(t) if l.startswith("shahid\t"))
    assert t[k - 1].endswith("\tوضع\tربط") and all(l.startswith("mudaa\t") for l in t[:k]), t[k - 2:k + 1]
    assert all(l.startswith("shahid\t") for l in t[k:]), t[k:]
    code, out = run("fahs", "--sijill", sj)
    assert code == 0, out
    ok += 1

    s[-1]["shawahid"][1][3] = "3"
    json.dump({"sijill": s}, open(sj, "w", encoding="utf-8"), ensure_ascii=False)
    code, out = run("fahs", "--sijill", sj)
    assert code == 1 and "لا تطابق بصمةَ المودَع" in out, out
    ok += 1
finally:
    shutil.rmtree(tmp)

t = open(os.path.join(HERE, "sijill.tsv"), encoding="utf-8").read().split("\n")[:-1]
sh = [i for i, l in enumerate(t) if l.startswith("shahid\t")]
assert len(sh) == 31 and sh == list(range(len(t) - 31, len(t))), (len(sh), sh[:3])
p = subprocess.run([sys.executable, "-I", os.path.join(os.path.dirname(HERE), "scripts", "bina_ribt.py"), "--check"],
                   capture_output=True, text=True)
assert p.returncode == 0 and p.stdout.startswith("مطابق"), p.stdout + p.stderr
ok += 1

print(f"{ok}/10")
