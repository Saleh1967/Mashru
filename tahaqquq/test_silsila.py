"""سلسلةُ الشهادات من النصّ إلى حكم الجملة (Nizam/Silsila.lean، والأداة `silsila` من Qari/Silsila.lean).

**وسمُ التوقّعات.** كتبها البنّاءُ لا مؤلّفٌ مستقلّ، وبعضُها بعد رؤية مخرج `silsila` أو `qari --itar`: أحكامُ f وg وq1 وq3 وc وi (حكمُ الأسماء
الستّة فيها كما يطبعه `qari --itar`)، ونصُّ رفض القارئ في r1، وأسماءُ القواعد في MAQATI، والبدائل. فهي في ١–٣ **مطابَقةٌ على مخرجٍ رآه البنّاء**
(حارسُ تراجع)، إلّا ما يشتقّه الرفعُ والعقدُ وحدهما من حكمٍ مسمّى: موضعُ الاسم المرفوع وسلسلتُه («كلمة 2 … ← مقطع 5 … ← قاعدة …»)، وأيُّ
الأحوال الثلاث لكلّ مانع، والمواضعُ بعدِّ النقاط. وتغيّرت ستّةُ توقّعات (بدائلُ a وg وq1 وq3، وحكما f وg) بعد مراجعة `murajii` حين صار الإطارُ
يدخل الجملةَ بشهادته، وتوقّعها البنّاءُ قبل التشغيل وطابقته. والمخرجُ سلوكُ المحرّك لا صوابُ اللغة: q1 («ذَهَبَ الْوَلَدُ ٱلْكَبِيرُ»، وهي صحيحة)
ممتنعةٌ لأنّ المحرّك يقرأ الصفةَ مفعولًا به. يفحص، بلا مودَع:
١. حكمُ الجملة: لكلّ جملةٍ في JUMAL حكمُ الفاحص على شهادتها، ومخرجُها، وبدائلُها (الإطاراتُ الأخرى غيرُ الممتنعة)؛ ومنه أنّ الناقصَ يظهر باسمه
   مسبوقًا باسم كلمته ومقطعه («كلمة 2 «مَدْرَسَةْ» ← مقطع 5 «ةْ» ← قاعدة التاء المربوطة») أو باسم إطاره ومانعه («إطار 1 (فعل فاعل) ← خلل قراءة
   الأسماء الستّة …»)، والفاسدَ باسم سببه؛ والإطاراتُ مقدّمةٌ لم تُفحص حيث لم يقرأ القارئُ كلمةً (h، r1، r3) ولا في غيرها.
٢. «انتفى» غيرُ «لم يُفحص»: موانعُ الإطار الستّة بأحوالها في ثلاث جمل (مكوّنٌ مرخِّصٌ مانعٌ منفيّ، وممتنعٌ مشهود، و«لا حكم» لم يُفحص).
٣. المواضع: مواضعُ الكلمات في الجملة ومقاطعِها في كلمتها، وقاعدةُ كلّ مقطع.
٤. الاتّساق (بين مخرجين للبرنامج، لا توقّعٌ مستقلّ؛ وهو ما تقوله `itar_murakhkhas` و`itar_mumtani` و`itar_laHukm` و`jumla_jamaa` إذا رُخّصت
   الكلماتُ كلُّها): على الجمل العشرين من JUMAL وITTISAQ التي كلماتُها مرخَّصةٌ كلُّها، حكمُ الفاحص على الجملة من صنف حكم `qari --itar` (مرخص ←
   مقبول، ممتنع ← خطأ، لا_تنطبق أو معلق ← لا_حكم)؛ وكلُّ إطارٍ حكمُ الفاحص عليه من صنف حكمه بصفّ الستّة، وكلاهما حقلان في سطر `silsila` نفسِه.
٥. السباكة (بلا دلالةٍ مستقلّة): كلُّ مقدّمةٍ مشهودةٍ أو منفيّةٍ لها سند — وهو تعريفُ `Muqaddima.halFiil`، فلا يكشف إلّا تغييرًا في الطابع —؛ وكلُّ
   جملةٍ وكلمةٍ مربوطةٌ (فرضُ `silsila_murakhkhas`) على JUMAL وITTISAQ.

الطفرات وقاتلُها: P1375 (اسمُ التعليق في الأداة، ١)، P1376 (رقمُ المقطع من الصفر في Nizam/Silsila.lean، ١)، P1377 (البدائلُ تشمل الممتنع، ١)،
P1378 (بدايةُ الكلمة بعد الفراغ، ٣)، P1379 (اسما الحالين مقلوبان في الأداة، ٢)؛ وعلى Lean يقتلها البناء: P1380 («لا حكم» مانعٌ منفيّ:
`halUtur_ghayr`)، P1381 (الابنُ المعلَّق يُرفع منفيًّا: `naqs_zahir`)، P1382 (قراءةُ القارئ المردودة شرطٌ مشهود: `shartQari_matlub`)، P1383
(خارجَ الحدّ لم يُفحص: `itar_ahwal`)؛ وP1384 (عقدةُ الإطارات ولو لم تُقرأ الكلمات) يقتلها ١: تُبنى، ولا يتغيّر بها حكمُ جملةٍ في JUMAL؛
وP1385 (الإطارُ المعلَّق يُرفع في الجملة منفيًّا) تُبنى (`rafaItar_hal` يقبل الحالين) ويقتلها ١ (f وg تصيران «لا_تنطبق»).
**ما لا يُعزل:** ٤ و٥ لا طفرةَ تعزلهما: ما يكسر ٤ في Lean يكسر مبرهناتِه قبله، وما يكسره في الأداة يكسر ١ قبله.
التشغيل: python3 -I tahaqquq/test_silsila.py
"""
import pathlib
import subprocess
import sys
import tempfile

JADHR = pathlib.Path(__file__).resolve().parent.parent
SILSILA = JADHR / ".lake" / "build" / "bin" / "silsila"
QARI = JADHR / ".lake" / "build" / "bin" / "qari"

# مفتاح: (جملة، حكمُ الجملة، مخرجُها، بدائلُها)
JUMAL = {
    "a": ("ذَهَبَ أَبُو الْوَلَدِ", "مرخص", "1 (فعل فاعل مضاف_إليه)", ""),
    "d": ("ذَهَبَ زَيْدٌ", "مرخص", "1 (فعل فاعل)", ""),
    "e": ("قَرَأَ الْوَلَدُ الْكِتَابَ", "مرخص", "1 (فعل فاعل مفعول_به)", ""),
    "j": ("فِي الدَّارِ", "مرخص", "1 (حرف_جر مجرور)", ""),
    "c": ("كَتَبَ", "لا_تنطبق: إطارٌ في المجال (Jisr.NassItar.itarat)", "", ""),
    "i": ("ذَهَبَ الْوَلَدُ ذَهَبَ ذَهَبَ", "لا_تنطبق: إطارٌ في المجال (Jisr.NassItar.itarat)", "", ""),
    "f": ("ذَهَبَ الْفَتَى", "معلق: إطار 1 (فعل فاعل) ← خلل قراءة الأسماء الستّة (Jisr.QawaidSitta.qiraaSitta)", "",
          "1 (فعل فاعل)"),
    "g": ("ذَهَبَ ذُو الْمَالِ", "معلق: إطار 1 (فعل فاعل مضاف_إليه) ← خلل قراءة الأسماء الستّة (Jisr.QawaidSitta.qiraaSitta)", "",
          "1 (فعل فاعل مضاف_إليه)"),
    "q1": ("ذَهَبَ الْوَلَدُ ٱلْكَبِيرُ", "ممتنع: الإطاراتُ كلُّها ممتنعة", "", ""),
    "q3": ("ذَهَبَ وَلَدْ", "ممتنع: الإطاراتُ كلُّها ممتنعة", "", ""),
    "h": ("ذَهَبَ زَيْدٌ ﷺ", "مدخل_فاسد: كلمة 3 «ﷺ» ← مقطع 1 «ﷺ» ← حرف ليس في جدول المخارج", "", ""),
    "r1": ("ذَهَبَ زَيْد", "مدخل_فاسد: كلمة 2 «زَيْد» ← قراءة القارئ على التحصيل (Dal.QiraaTahsil.qiraa): الحرف الأخير بلا حركة في "
           "غير آخر الجملة: «د» — الوصل يحتاج حركته", "", ""),
    "r2": ("ذَهَبَ مَدْرَسَةْ", "معلق: كلمة 2 «مَدْرَسَةْ» ← مقطع 5 «ةْ» ← قاعدة التاء المربوطة", "", "1 (فعل فاعل)"),
    "r3": ("ذَهَبَ الْوَلَـَدُ", "معلق: كلمة 2 «الْوَلَـَدُ» ← مقطع 5 «ـَ» ← قاعدة التطويل بعلامة", "", ""),
}

# جملٌ للاتّساق وحده (٤).
ITTISAQ = ["ضَرَبَ الرَّجُلُ أَبَا الْوَلَدِ", "جَاءَ أَبُوكَ", "رَأَيْتُ أَخَاكَ", "مَرَرْتُ بِأَبِيكَ", "ذَهَبَ حَمُو الْمَرْأَةِ",
           "جَاءَ ذُو مَالٍ", "ضَرَبَ زَيْدٌ عَمْرًا", "فِي بَيْتٍ", "ذَهَبَ أَبِي الْوَلَدِ", "جَاءَ أَخُو زَيْدٍ"]

# موانعُ الإطار بأحوالها (٢): مفتاح، رقمُ الإطار ← {اسمُ المانع بادئةً: الحال}
MAWANI = {
    ("f", "1"): {"خلل قراءة الأسماء الستّة": "لم_يفحص", "خلل الوصل بخانات المالك": "منفي", "خلل الابتداء": "منفي",
                 "خلل التركيب": "منفي", "خلل وصل المدلول": "منفي", "خلل الوقف": "منفي"},
    ("q1", "1"): {"خلل الوصل بخانات المالك": "مشهود", "خلل الابتداء": "منفي"},
    ("a", "1"): {"خلل قراءة الأسماء الستّة": "منفي", "خلل الوصل بخانات المالك": "منفي"},
}

# المواضع (٣): مفتاح ← [(رقم، كلمة، بداية-نهاية)]، و(رقم.رقم) ← (مقطع، بداية-نهاية، قاعدة)
KALIMAT = {"a": [("1", "ذَهَبَ", "0-6"), ("2", "أَبُو", "7-12"), ("3", "الْوَلَدِ", "13-22")],
           "i": [("1", "ذَهَبَ", "0-6"), ("2", "الْوَلَدُ", "7-16"), ("3", "ذَهَبَ", "17-23"), ("4", "ذَهَبَ", "24-30")]}
MAQATI = {("a", "3.1"): ("ا", "0-1", "Dal.Tahsil.hamzaWaslAl"), ("a", "3.2"): ("لْ", "1-3", "Dal.Tahsil.harfHaraka"),
          ("a", "2.3"): ("و", "4-5", "Dal.Tahsil.harfMadd"), ("d", "2.3"): ("دٌ", "4-6", "Dal.Tahsil.tanwin"),
          ("r2", "2.5"): ("ةْ", "8-10", "Dal.Tahsil.tasnif")}

LAM_TUQRA = "الإطارات: لم تُحسب، فكلمةٌ لم يقرأها القارئ"
SINF = {"مرخص": "مقبول", "ممتنع": "خطأ", "لا_تنطبق": "لا_حكم", "معلق": "لا_حكم"}

fashal = []
najah = 0


def tahaqqaq(shart, risala):
    global najah
    if shart:
        najah += 1
    else:
        fashal.append(risala)


def shaghghil(bin_, asatir):
    with tempfile.NamedTemporaryFile("w", suffix=".tsv", delete=False, encoding="utf-8") as f:
        f.write("".join(f"{k}\t{s}\n" for k, s in asatir))
        p = f.name
    r = subprocess.run([str(bin_), *([] if bin_ == SILSILA else ["--itar"]), p], capture_output=True, text=True, cwd=JADHR)
    pathlib.Path(p).unlink()
    if r.returncode != 0:
        sys.exit(f"{bin_.name} خرج {r.returncode}: {r.stderr}")
    return [l.split("\t") for l in r.stdout.splitlines()]


def sinf(h):
    return h.split(":")[0]


def main():
    for b in (SILSILA, QARI):
        if not b.exists():
            sys.exit(f"{b} غير مبنيّ: lake build")
    asatir = [(k, v[0]) for k, v in JUMAL.items()] + [(f"t{i}", s) for i, s in enumerate(ITTISAQ)]
    out = shaghghil(SILSILA, asatir)
    itar = {l[0]: l for l in shaghghil(QARI, asatir)}
    jumla = {l[0]: l for l in out if l[1] == "JUMLA"}
    kal = {}
    for l in out:
        if l[1] == "KALIMA":
            kal.setdefault(l[0], []).append(l)

    # ١
    for k, (_, h, mkh, bad) in JUMAL.items():
        l = jumla.get(k)
        tahaqqaq(l is not None and l[3] == h, f"١ {k}: الحكم {l[3] if l else None!r} لا {h!r}")
        tahaqqaq(l is not None and l[4] == mkh, f"١ {k}: المخرج {l[4] if l else None!r} لا {mkh!r}")
        tahaqqaq(l is not None and l[5] == bad, f"١ {k}: البدائل {l[5] if l else None!r} لا {bad!r}")

    for k in JUMAL:
        x = [l for l in out if l[0] == k and l[1] == "MUQ" and l[2] == "jumla" and l[5] == LAM_TUQRA]
        tahaqqaq(len(x) == (k in {"h", "r1", "r3"}) and all(l[3:5] == ["شرط", "لم_يفحص"] for l in x),
                 f"١ {k}: مقدّمةُ «{LAM_TUQRA}» {[l[3:5] for l in x]}")

    # ٢
    for (k, i), mm in MAWANI.items():
        muq = [l for l in out if l[0] == k and l[1] == "MUQ" and l[2] == f"itar {i}" and l[3] == "مانع"]
        for ism, hal in mm.items():
            x = [l for l in muq if l[5].startswith(ism)]
            tahaqqaq(len(x) == 1 and x[0][4] == hal, f"٢ {k} إطار {i}: «{ism}» {[l[4] for l in x]} لا {hal}")
        tahaqqaq(len(muq) == 6, f"٢ {k} إطار {i}: {len(muq)} مانعًا لا 6")

    # ٣
    for k, ks in KALIMAT.items():
        got = [(l[2], l[3], l[4]) for l in kal.get(k, [])]
        tahaqqaq(got == ks, f"٣ {k}: الكلمات {got} لا {ks}")
    for (k, n), (nass, mawdi, qaida) in MAQATI.items():
        x = [l for l in out if l[0] == k and l[1] == "MAQTA" and l[2] == n]
        tahaqqaq(len(x) == 1 and x[0][3:6] == [nass, mawdi, qaida], f"٣ {k} {n}: {x[0][3:6] if x else None} لا {[nass, mawdi, qaida]}")

    # ٤
    nisab = 0
    for k, _ in asatir:
        if k not in jumla or not kal.get(k) or not all(l[6] == "مرخص" for l in kal[k]):
            continue
        nisab += 1
        q = itar.get(k)
        tahaqqaq(q is not None and SINF[sinf(jumla[k][3])] == q[1], f"٤ {k}: الجملة {jumla[k][3]} و--itar {q[1] if q else None}")
        for l in out:
            if l[0] == k and l[1] == "ITAR":
                tahaqqaq(SINF[sinf(l[5])] == l[4], f"٤ {k} إطار {l[2]}: الفاحص {l[5]} وحكمُ الستّة {l[4]}")
    tahaqqaq(nisab == 20, f"٤: {nisab} جملةً كلماتُها مرخَّصة، لا 20")

    # ٥
    for l in out:
        if l[1] == "MUQ":
            tahaqqaq(l[6] != "" or l[4] == "لم_يفحص", f"٥ {l[0]} {l[2]}: «{l[5]}» {l[4]} بلا سند")
        if l[1] == "JUMLA":
            tahaqqaq(l[2] == "1", f"٥ {l[0]}: الجملة غير مربوطة")
        if l[1] == "KALIMA":
            tahaqqaq(l[5] == "1", f"٥ {l[0]} كلمة {l[2]}: غير مربوطة")

    if fashal:
        print("\n".join("FAIL " + x for x in fashal))
        print(f"{najah} نجح، {len(fashal)} فشل")
        sys.exit(1)
    print(f"test_silsila: {najah} فحصًا نجح ({nisab} جملةً في الاتّساق)")


if __name__ == "__main__":
    main()
