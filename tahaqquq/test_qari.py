def hukm_saffs(o):
    """أسطرُ الحكم بالشواهد: (النوع، الجذر الآخر، المعجم والسطر، الحكم)."""
    out = []
    for l in o:
        if l.startswith("      ") and " ← «" in l:
            naw, rest = l.strip().split(" ← «", 1)
            b_, rest = rest.split("» بلفظ «", 1)
            _, rest = rest.split("»: ", 1)
            hukm = "مرخَّص" if rest.startswith("مرخَّص") else rest.split(" (")[0]
            out.append((naw, b_, rest[rest.rindex("(") + 1:-1], hukm))
    return out


QANUN = "    القانون (إطار الدالّ dalOK = القانونان معًا، dalOK_taqatu؛ بجدول البتّات runB): "
QADIM = "  على الخلايا كما هي (موقوفًا عليها Fwaqf ∘ run: مكوّنُ القانون dalOK؛ وفي الوصل Fwasl ∘ run: ليس من القانون — وصلُ dalOK غيرُ فارغةٍ و run ≠ 96، wasl_ghayr_Fwasl): موقوفًا عليها "


def qanun_juz(o):
    """(العقد، على الخلايا كما هي، بعد تسكين الآخر) من سطر القانون."""
    jadid = [l for l in o if l.startswith(QANUN)]
    assert len(jadid) == 1, o
    l = jadid[0][len(QANUN):]
    aqd, rest = l.split(" — على الخلايا كما هي (Fwaqf ∘ run): ")
    kama, baad = rest.split("؛ بعد تسكين الآخر (complete'): ")
    return aqd == "مقبولة", kama == "مقبولة", baad == "مقبولة"


def muwafaqat_qanun(o):
    """مكوّنُ «على الخلايا» بجدول البتّات وسطرُ «على الخلايا كما هي» بـ run (موقوفًا عليها) واحد، والعقدُ هو المكوّنان معًا (اتّساقُ مخرجين)."""
    qadim = [l[len(QADIM):] for l in o if l.startswith(QADIM)]
    assert len(qadim) == 1, o
    aqd, kama, baad = qanun_juz(o)
    hukm = qadim[0].split("؛")[0]
    assert hukm in ("مرخَّصة", "ممتنعة"), qadim[0]
    return (hukm == "مرخَّصة") == kama and aqd == (kama and baad)


