PREFIXES = ("### | ", "# ", "~~")


def strip(line):
    for p in PREFIXES:
        if line.startswith(p):
            return line[len(p):]
    return line


def lines(name):
    with open(os.path.join(SRC, name), encoding="utf-8") as f:
        return f.read().split("\n")


Q = lines("qatr.txt")
A = lines("alfiyya.txt")


def q(n, nass):
    t = strip(Q[n - 1])
    assert nass in t, (n, nass)
    return {"masdar": "قطر", "satr": n, "nass": nass}


def a(n, nass):
    t = strip(A[n - 1])
    assert nass in t, (n, nass)
    return {"masdar": "ألفية", "satr": n, "nass": nass}


