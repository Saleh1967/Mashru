def bina():
    out = []
    for (n, fia, mithal, harfi, asl, mu, mw, bd, hlk, hk, zawj, sanad, taliq) in C:
        sn = []
        for k in sanad:
            m, s, nass = S[k]
            satr = jarrid(SATR[m][s - 1])
            assert nass in satr, (n, k)
            sn.append({"masdar": m, "satr": s, "nass": nass})
        fi = any(mithal in jarrid(SATR[p["masdar"]][p["satr"] - 1]) for p in sn)
        assert fi == harfi, (n, mithal, fi, harfi)
        out.append({
            "id": "I%02d" % n,
            "fia": fia,
            "mithal": mithal,
            "mithal_harfi": harfi,
            "dakhil": {"asl": asl, "mushar": MUSHAR[mu], "mawdi": MAWDI[mw], "bud": BUD[bd],
                       "ha": hlk[0] == "h", "lam": hlk[1] == "l", "kaf": hlk[2] == "k"},
            "hukm": HUKM[hk],
            "zawj": None if zawj is None else "I%02d" % zawj,
            "sanad": sn,
            "taliq": taliq,
        })
    return out


if __name__ == "__main__":
    data = bina()
